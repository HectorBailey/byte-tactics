def place_debug_directory(placer: Placer) -> None:
    """LINK writes its debug directory into .rdata right after the import
    address table; its contents (link_image) wait for the file's layout."""
    iat = [p for p in placer.pieces if p.sec.name == ".idata$5"]
    va = max(p.va + p.hi - p.lo for p in iat)
    import pe
    size = pe.DEBUG_ENTRY * 3
    placer.img.write(va, bytes(size), DEBUGDIR)
    placer.debug_directory = va


def image_sections(placer: Placer, settings: dict) -> list:
    """The output sections, from what is placed: LINK starts each at the
    section alignment after the one before, so a section runs from such a
    boundary to its last byte before a gap that reaches the next boundary.
    It is named for its first piece's input section (the import address
    table's .idata$5 opens .rdata, the C runtime's .CRT$XIA opens .data), its
    raw data runs to its last piece of initialised data, at the file
    alignment, and its characteristics are those of its input sections of
    its own name, less their alignment and COMDAT flags. The tree's objects
    do not always put a piece in the section the original had it in (a
    string the original kept in .rdata, one of the tree's objects in .data),
    so the names of the pieces inside say less than where they are."""
    import pe
    img = placer.img
    align = settings["section_alignment"]
    src = img.src
    by_start = sorted(placer.pieces, key=lambda p: p.va)
    sections = []
    o = align
    while o < img.size:
        while o < img.size and src[o] == UNSET:
            o += 1
        if o >= img.size:
            break
        start = o
        while True:
            while o < img.size and src[o] != UNSET:
                o += 1
            # A gap: the section ends here unless something is placed before
            # the next section boundary.
            boundary = min(pe.align(o, align), img.size)
            nxt = o
            while nxt < boundary and src[nxt] == UNSET:
                nxt += 1
            if nxt >= boundary:
                break
            o = nxt
        end = o
        inside = [q for q in by_start if start <= q.va - img.base < end]
        first = OUTPUT_SECTIONS.get(inside[0].sec.name.split("$", 1)[0], inside[0].sec.name)
        initialised = [q for q in inside if not q.sec.chars & SCN_UNINIT]
        raw_end = max(q.va + q.hi - q.lo for q in initialised) - img.base if initialised else start
        own = [q for q in inside if q.sec.name.split("$", 1)[0] == first] or inside
        chars = own[0].sec.chars & 0xFE0000E0
        sections.append(pe.Section(first, start, end - start, pe.align(raw_end - start, settings["file_alignment"]),
                                   chars))
        o = pe.align(end, align)
    return sections


def fpo_records(placer: Placer) -> list[bytes]:
    """Every placed function's frame pointer omission record (FPO_DATA), from
    its object's .debug$F with the function's address in it, sorted by
    address as LINK sorts them. A record whose relocation names an undefined
    symbol (the compiler's scalar deleting destructors refer to their own
    function so) means the definition of that name in the same object."""
    records = {}
    for p in placer.pieces:
        if not p.sec.is_code:
            continue
        obj = p.obj
        for sec in obj.secs:
            if sec.name != ".debug$F":
                continue
            for off, symidx, rtype in sec.relocs:
                sym = obj.syms[symidx]
                if sym.section == 0 and sym.name in obj.externals:
                    sym = obj.externals[sym.name]
                (addend,) = struct.unpack_from("<I", sec.data, off)
                at = sym.value + addend
                if rtype != REL_DIR32NB or sym.section != p.sec.index or not p.lo <= at < p.hi:
                    continue
                rva = p.va + at - p.lo - placer.img.base
                record = bytearray(sec.data[off:off + 16])
                struct.pack_into("<I", record, 0, rva)
                records[rva] = bytes(record)
    return [records[rva] for rva in sorted(records)]


def link_image(placer: Placer, settings: dict, sections: list):
    """The image as the headers describe it, and the debug records. The
    debug directory's contents go into the image here, now that the file's
    layout says where the records are."""
    import pe
    img = placer.img
    imports = [p for p in placer.pieces if p.sec.name in (".idata$2", ".idata$3")]
    iat = [p for p in placer.pieces if p.sec.name == ".idata$5"]
    rsrc = next(x for x in sections if x.name == ".rsrc")
    entry = placer.globals.get(settings["entry"])
    if entry is None:
        raise SystemExit(f"no placed function is the entry point {settings['entry']}")
    directories = {
        pe.DIR_IMPORT: (min(p.va for p in imports) - img.base, sum(p.hi - p.lo for p in imports)),
        pe.DIR_RESOURCE: (rsrc.rva, rsrc.vsize),
        pe.DIR_DEBUG: (placer.debug_directory - img.base, 3 * pe.DEBUG_ENTRY),
        pe.DIR_TLS: (placer.tls_directory - img.base, 24),
        pe.DIR_IAT: (min(p.va for p in iat) - img.base, sum(p.hi - p.lo for p in iat)),
    }
    rich = [(0, settings["unmarked_objects"])]
    compid = placer.resources.absolutes.get("@comp.id") if placer.resources else None
    if compid is None and placer.resources:
        compid = next((s.value for s in placer.resources.syms.values() if s.name == "@comp.id"), None)
    if compid is not None:
        rich.append((compid, 1))
    image = pe.Image(sections, entry - img.base, directories, fpo_records(placer), rich)
    records = pe.debug_records(settings, image.fpo)
    pointer = pe.layout_file(settings, image)
    directory = pe.debug_directory(settings, records, pointer)
    o = placer.debug_directory - img.base
    img.out[o:o + len(directory)] = directory
    return image, records


def write_exe(placer: Placer, settings: dict, out: Path) -> bytes:
    """The exe: the generated headers, each section's raw data from the
    image, and the debug records after them (tools/pe.py)."""
    import pe
    img = placer.img
    contents = {x.name: bytes(img.out[x.rva:x.rva + x.raw]) for x in placer.exe.sections}
    return pe.write(out, settings, placer.exe, contents, placer.debug_records)


def write_map(placer: Placer, out: Path) -> None:
    rows = sorted((p.va, p.hi - p.lo, SOURCES[p.source], p.label, p.obj.path.name) for p in placer.pieces)
    with out.open("w") as fh:
        fh.write("address,size,source,symbol,object\n")
        for va, size, source, label, obj in rows:
            fh.write(f"{va:#x},{size},{source},{label},{obj}\n")


# --- the report ---------------------------------------------------------------------

def compare(img: Image, placer: Placer, verbose: bool) -> tuple[int, list[str]]:
    """Bytes of the built image that differ from the original, by source."""
    def label(va: int) -> str:
        pid = img.owner[va - img.base]
        if not pid:
            return ""
        p = placer.pieces[pid - 1]
        return f"{p.label}+{va - p.va:#x}" + (f" (placed for {p.why})" if p.why else "")

    patched = set()
    for at, size, _ in img.patches:
        patched.update(range(at - img.base, at - img.base + size))
    lines, total, by_source, run = [], 0, Counter(), None
    for name, start, vsize, rsize, _ in img.sections:
        lo, hi = start - img.base, start - img.base + max(vsize, rsize)
        for i in range(lo, hi + 1):
            differs = i < hi and img.out[i] != img.orig[i] and i not in patched
            if differs:
                total += 1
                by_source[SOURCES[img.src[i]]] += 1
                if run is None:
                    run = i
            elif run is not None:
                va = img.base + run
                lines.append(f"  {va:#x}..{img.base + i:#x} ({i - run} bytes, {SOURCES[img.src[run]]}) {label(va)}")
                run = None
    out = [f"bytes that differ from the original, outside data/exe_patches.csv: {total:,}"]
    out += [f"  {k}: {v:,}" for k, v in by_source.most_common()]
    patch_diff = sum(1 for i in patched if img.out[i] != img.orig[i])
    if img.patches:
        out.append(f"bytes under data/exe_patches.csv that differ from the original: {patch_diff:,} "
                   "(GOG's patch is applied after the link; --no-exe-patches leaves the compiler's bytes)")
    shown = lines if verbose else lines[:20] + (["  ..."] if len(lines) > 20 else [])
    return total, out + shown


def report(img: Image, placer: Placer, verbose: bool) -> int:
    print("placement:")
    for k, v in sorted(placer.stats.items()):
        print(f"  {k}: {v:,}")
    counts = Counter()
    for x in placer.exe.sections:
        for i in range(x.rva, x.rva + max(x.vsize, x.raw)):
            counts[(x.name, img.src[i])] += 1
    print("where each section's bytes come from:")
    for x in placer.exe.sections:
        parts = [f"{SOURCES[s]} {counts[(x.name, s)]:,}" for s in range(len(SOURCES)) if counts[(x.name, s)]]
        print(f"  {x.name:6} {max(x.vsize, x.raw):>9,}: " + ", ".join(parts))
    headers = placer.exe.sections[0].pointer
    debug = sum(len(data) for _, data in placer.debug_records)
    print(f"  headers {headers:,} and debug records {debug:,} (after the sections): generated (tools/pe.py)")
    limit = None if verbose else 15
    for title, items in (("relocations that disagree with the original, and missing definitions", placer.mismatches),
                         ("pieces that differ from a piece already placed there", placer.clashes),
                         ("library functions data/functions.csv names differently", placer.renamed)):
        if items:
            print(f"{title}: {len(items):,}")
            for m in items[:limit]:
                print("  " + m)
    if img.copied_library:
        print(f"library functions copied, with no member placed: {len(img.copied_library):,}")
        for addr, name in img.copied_library[:limit]:
            print(f"  {addr:#x} {name}")
    if placer.unresolved:
        print(f"names whose address only the original's bytes give: {len(placer.unresolved):,}")
        for name, n in placer.unresolved.most_common(limit):
            print(f"  {name} ({n})")
    total, lines = compare(img, placer, verbose)
    print("\n".join(lines))
    return total


def layout(jobs: int | None = None) -> tuple[Image, Placer]:
    """Lay the tree out at the original's addresses: the image and every
    placed piece. Other tools use it as a map of what each address holds."""
    paths, failed = compile_all(jobs)
    if failed:
        raise SystemExit(f"{len(failed)} file(s) did not compile; tools/link.py lists them")
    symbols = load_symbols()
    # src/lib/ is runtime library code: placed with the library members.
    lib_objs = ROOT / "build/progress" / LIB_DIR.relative_to(ROOT / "src")
    lib_paths = [p for p in paths if p.is_relative_to(lib_objs)]
    paths = [p for p in paths if not p.is_relative_to(lib_objs)]
    objects = [parse(p) for p in paths]
    by_src = {}
    for p, obj in zip(paths, objects):
        by_src[str(Path("src") / p.relative_to(ROOT / "build/progress").with_suffix(".cpp"))] = obj

    img = Image(ROOT / "orig/TotalA.exe")
    placer = Placer(img, objects, symbols)
    library_names(placer)
    place_functions(placer, by_src)
    place_gaps(placer, gap_objects())
    place_library(placer, lib_paths)
    place_imports(placer)
    place_import_thunks(placer)
    place_tls(placer)
    place_tree_globals(placer, by_src)
    place_data_sources(placer, by_src)
    data_objs, data_addr = build_data(symbols)
    place_globals(placer, data_objs, data_addr)
    placer.relocate()
    place_unreferenced_library(placer)
    placer.relocate()
    place_section_rest(placer)
    placer.relocate()
    place_member_data(placer)
    placer.relocate()
    place_crt_tables(placer)
    place_commons(placer)
    pad_data(placer)
    place_resources(placer)
    placer.relocate()
    place_debug_directory(placer)
    from pe import settings
    link = settings()
    sections = image_sections(placer, link)
    placer.exe, placer.debug_records = link_image(placer, link, sections)
    copy_unbuilt(img, sections)
    return img, placer


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", type=Path, default=OUT_DIR / "TotalA.exe")
    ap.add_argument("--jobs", type=int, default=None, help="parallel compiles (default: all cores)")
    ap.add_argument("--strict", action="store_true", help="exit non-zero if any built byte differs")
    ap.add_argument("--no-exe-patches", action="store_true",
                    help="leave out data/exe_patches.csv (GOG's no-CD music patch): the compiler's bytes")
    ap.add_argument("--art", type=Path,
                    help="the directory with the game's icon and cursor (TotalA.ico, TotalA.cur) for the "
                         "resources (default: BT_ART_DIR, or extracted from orig/TotalA.exe)")
    ap.add_argument("--verbose", "-v", action="store_true")
    args = ap.parse_args()
    if args.art:
        import os
        os.environ["BT_ART_DIR"] = str(args.art.resolve())
    output = args.output if args.output.is_absolute() else ROOT / args.output

    img, placer = layout(args.jobs)
    if not args.no_exe_patches:
        from exepatch import apply_placed
        apply_placed(img.out, img.base)
    from pe import settings
    data = write_exe(placer, settings(), output)
    write_map(placer, output.with_suffix(".map"))
    total = report(img, placer, args.verbose)
    original = bytes(img.pe.__data__)
    differ = sum(a != b for a, b in zip(data, original)) + abs(len(data) - len(original))
    print(f"{output.relative_to(ROOT)}: {len(data):,} bytes, {differ:,} of them differ from orig/TotalA.exe "
          f"(headers {sum(a != b for a, b in zip(data[:0x400], original[:0x400])):,})")
    total += differ
    if args.strict and total:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
